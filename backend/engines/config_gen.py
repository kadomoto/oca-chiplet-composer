"""Harness configuration generated from a design.

Bringing up dies that talk over AXI-over-UCIe needs setup that is easy to get
wrong by hand:

  * a package-level address map: each chiplet's SMC global window, 16 MiB
    aligned and 32 MiB apart (window + M-mode and Xvisor outbound remap windows),
    below the SEP aperture at 0x5000_0000;
  * SMC inbound filter entries, since the filter blocks by default: each die
    opens its mailbox page to non-secure traffic from the peers it links to;
  * AoU activation order: on each link, one side activates (which auto-acks the
    peer) and the other waits for ENABLED before it sends anything.

This module derives all of it from the design and renders it as
  * a package config (JSON) for the GUI and the export bundle,
  * one C header per die of a link run (firmware/oca-d2d-pingpong reads it),
  * the `mdie.die<k>.smc_global_base` ini keys that mdie-vp reads.
"""
from __future__ import annotations

GLOBAL_BASE0 = 0x4000_0000
FOOTPRINT = 0x0200_0000          # 16 MiB window + 8 MiB M-mode + 8 MiB Xvisor remap
WINDOW = 0x0100_0000             # the SMC global window itself
SEP_APERTURE = (0x5000_0000, 0x2000_0000)
MAX_DIES = (SEP_APERTURE[0] - GLOBAL_BASE0) // FOOTPRINT      # 8
SPM_OFF = 0x0006_0000            # scratchpad inside the SMC map
MAILBOX_OFF = SPM_OFF + 0x3100   # the d2d mailbox cells
FILTER_CFG_RW_NS_4K = 0x0100_0113  # read, write, enable, allow_ns, 4 KiB granularity


def address_map(design: dict) -> list[dict]:
    """Chiplets in design order get consecutive 32 MiB global slots."""
    rows = []
    for k, c in enumerate(design["chiplets"]):
        base = GLOBAL_BASE0 + k * FOOTPRINT
        rows.append({
            "chiplet": c["id"], "name": c["name"], "index": k,
            "smc_global_base": base, "smc_global_end": base + WINDOW - 1,
            "remap_windows": [base + WINDOW, base + FOOTPRINT - 1],
            "fits": k < MAX_DIES,
        })
    return rows


def issues(design: dict) -> list[dict]:
    n = len(design["chiplets"])
    if n > MAX_DIES:
        return [{"severity": "error", "ref": design["chiplets"][MAX_DIES]["id"],
                 "message": f"The Harness global address map holds {MAX_DIES} chiplets below the SEP "
                            f"aperture (32 MiB each from 0x4000_0000); this design has {n}. "
                            f"Remove {n - MAX_DIES} or split the package."}]
    return []


def _mailbox_page(base: int) -> tuple[int, int]:
    lo = (base + MAILBOX_OFF) & ~0xFFF
    return lo, lo + 0xFFF


def package_config(design: dict) -> dict:
    amap = address_map(design)
    by_id = {r["chiplet"]: r for r in amap}
    links, filters = [], {r["chiplet"]: [] for r in amap}
    for l in design["links"]:
        a, b = by_id.get(l["a"]), by_id.get(l["b"])
        if not a or not b or a is b:
            continue
        init, resp = (a, b) if a["index"] <= b["index"] else (b, a)
        links.append({"link": l["id"], "initiator": init["chiplet"], "responder": resp["chiplet"],
                      "initiator_name": init["name"], "responder_name": resp["name"]})
        for me, peer in ((a, b), (b, a)):
            lo, hi = _mailbox_page(me["smc_global_base"])
            if not any(f["start"] == lo for f in filters[me["chiplet"]]):
                filters[me["chiplet"]].append({"entry": len(filters[me["chiplet"]]), "start": lo, "end": hi,
                                               "config": FILTER_CFG_RW_NS_4K, "allows": [peer["name"]],
                                               "purpose": "d2d mailbox page"})
            else:
                f = next(f for f in filters[me["chiplet"]] if f["start"] == lo)
                if peer["name"] not in f["allows"]:
                    f["allows"].append(peer["name"])
    return {"address_map": amap, "links": links, "inbound_filters": filters,
            "limits": {"max_dies": MAX_DIES, "footprint": FOOTPRINT, "sep_aperture": list(SEP_APERTURE)},
            "issues": issues(design)}


def _h(v: int) -> str:
    return f"0x{v:08X}ULL"


def pair_header(self_row: dict, peer_row: dict, die_index: int, initiator: bool, filt: list[dict]) -> str:
    """C header for one die of a two-die link run (firmware/oca-d2d-pingpong)."""
    lines = [
        "/* Generated by OCA Chiplet Composer (backend/engines/config_gen.py). Do not edit. */",
        "#pragma once",
        f"#define OCA_DIE_INDEX        {die_index}u          /* position in this mdie-vp run */",
        f'#define OCA_CHIPLET_NAME     "{self_row["name"]}"',
        f'#define OCA_PEER_NAME        "{peer_row["name"]}"',
        f"#define OCA_SELF_GLOBAL_BASE {_h(self_row['smc_global_base'])}   /* SMC fabric GLOBAL_BASE */",
        f"#define OCA_PEER_GLOBAL_BASE {_h(peer_row['smc_global_base'])}",
        f"#define OCA_MAILBOX_OFF      {_h(MAILBOX_OFF)}   /* d2d cells inside the SMC map */",
        f"#define OCA_AOU_INITIATOR    {1 if initiator else 0}u          /* 1: activate the AoU; 0: wait for ENABLED */",
        f"#define OCA_IB_FILTER_COUNT  {len(filt)}u",
    ]
    for i, f in enumerate(filt):
        lines += [f"#define OCA_IB_FILTER{i}_START {_h(f['start'])}",
                  f"#define OCA_IB_FILTER{i}_END   {_h(f['end'])}",
                  f"#define OCA_IB_FILTER{i}_CFG   0x{f['config']:08X}u   /* {f['purpose']}, allows {', '.join(f['allows'])} */"]
    return "\n".join(lines) + "\n"


def link_run(design: dict, pkg: dict, link_id: str) -> dict | None:
    """Everything one mdie-vp run of a link needs: die order, headers and ini keys."""
    lk = next((x for x in pkg["links"] if x["link"] == link_id), None)
    if lk is None:
        return None
    by_id = {r["chiplet"]: r for r in pkg["address_map"]}
    d0, d1 = by_id[lk["initiator"]], by_id[lk["responder"]]
    # each die of the run opens only the entry its peer in this run needs
    f0 = [dict(f, entry=0, allows=[d1["name"]]) for f in pkg["inbound_filters"][d0["chiplet"]][:1]]
    f1 = [dict(f, entry=0, allows=[d0["name"]]) for f in pkg["inbound_filters"][d1["chiplet"]][:1]]
    return {
        "dies": [d0, d1],
        "headers": [pair_header(d0, d1, 0, True, f0), pair_header(d1, d0, 1, False, f1)],
        "ini": {"mdie.die0.smc_global_base": d0["smc_global_base"],
                "mdie.die1.smc_global_base": d1["smc_global_base"]},
    }


def chiplet_header(pkg: dict, chiplet_id: str) -> str:
    """Package-level header for one chiplet: its window, its peers and its filter entries."""
    by_id = {r["chiplet"]: r for r in pkg["address_map"]}
    me = by_id[chiplet_id]
    peers = [(lk, lk["responder"] if lk["initiator"] == chiplet_id else lk["initiator"])
             for lk in pkg["links"] if chiplet_id in (lk["initiator"], lk["responder"])]
    out = ["/* Generated by OCA Chiplet Composer (backend/engines/config_gen.py). Do not edit. */",
           "#pragma once",
           f'#define OCA_CHIPLET_NAME     "{me["name"]}"',
           f"#define OCA_SELF_GLOBAL_BASE {_h(me['smc_global_base'])}",
           f"#define OCA_LINK_COUNT       {len(peers)}u"]
    for i, (lk, pid) in enumerate(peers):
        p = by_id[pid]
        out += [f'#define OCA_LINK{i}_PEER_NAME   "{p["name"]}"',
                f"#define OCA_LINK{i}_PEER_BASE   {_h(p['smc_global_base'])}",
                f"#define OCA_LINK{i}_INITIATOR   {1 if lk['initiator'] == chiplet_id else 0}u"]
    filt = pkg["inbound_filters"][chiplet_id]
    out.append(f"#define OCA_IB_FILTER_COUNT  {len(filt)}u")
    for i, f in enumerate(filt):
        out += [f"#define OCA_IB_FILTER{i}_START {_h(f['start'])}",
                f"#define OCA_IB_FILTER{i}_END   {_h(f['end'])}",
                f"#define OCA_IB_FILTER{i}_CFG   0x{f['config']:08X}u   /* allows {', '.join(f['allows'])} */"]
    return "\n".join(out) + "\n"
