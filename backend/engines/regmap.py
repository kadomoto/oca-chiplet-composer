def _num(s: str) -> int:
    return int(s, 0)


def parse_script(text: str, rm: dict) -> tuple[list[dict], list[str]]:
    """Compile a register script into ops. One statement per line, # starts a comment:

        write REG VALUE | write REG FIELD[|FIELD...]   (fields set their bits)
        read REG
        poll REG.FIELD [VALUE] [timeout N]             (default VALUE: all field bits set)
        poll REG VALUE [timeout N]
        expect REG[.FIELD] VALUE
        wait NS
    """
    regs = {r["name"]: r for r in rm.get("registers", [])}
    ops, errs = [], []

    def target(tok: str, ln: int):
        name, _, fld = tok.partition(".")
        r = regs.get(name)
        if r is None:
            errs.append(f"Line {ln}: no register named {name}.")
            return None, None, None
        mask, shift = 0xFFFFFFFF, 0
        if fld:
            f = next((f for f in r.get("fields", []) if f["name"] == fld), None)
            if f is None:
                errs.append(f"Line {ln}: {name} has no field {fld}.")
                return None, None, None
            shift = int(f["lsb"])
            mask = ((1 << int(f.get("width", 1))) - 1) << shift
        return r, mask, shift

    for ln, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        t = line.split()
        op = t[0].lower()
        try:
            if op == "write" and len(t) >= 3:
                r, _, _ = target(t[1], ln)
                if r is None:
                    continue
                if re.fullmatch(r"-?(0x[0-9a-fA-F]+|\d+)", t[2]):
                    val = _num(t[2]) & 0xFFFFFFFF
                else:
                    val = 0
                    for fn in t[2].split("|"):
                        f = next((f for f in r.get("fields", []) if f["name"] == fn), None)
                        if f is None:
                            errs.append(f"Line {ln}: {r['name']} has no field {fn}.")
                            break
                        val |= ((1 << int(f.get("width", 1))) - 1) << int(f["lsb"])
                ops.append({"op": "write", "reg": r["name"], "off": int(r["offset"]), "mask": 0xFFFFFFFF, "value": val, "timeout": 0})
            elif op == "read" and len(t) == 2:
                r, _, _ = target(t[1], ln)
                if r is not None:
                    ops.append({"op": "read", "reg": r["name"], "off": int(r["offset"]), "mask": 0xFFFFFFFF, "value": 0, "timeout": 0})
            elif op in ("poll", "expect") and len(t) >= 2:
                r, mask, shift = target(t[1], ln)
                if r is None:
                    continue
                rest = t[2:]
                timeout = 200000
                if "timeout" in rest:
                    i = rest.index("timeout")
                    timeout = _num(rest[i + 1])
                    rest = rest[:i] + rest[i + 2:]
                if rest:
                    val = (_num(rest[0]) << shift) & mask
                elif op == "poll":
                    val = mask
                else:
                    errs.append(f"Line {ln}: expect needs a value.")
                    continue
                ops.append({"op": op, "reg": t[1], "off": int(r["offset"]), "mask": mask, "value": val, "timeout": timeout})
            elif op == "wait" and len(t) == 2:
                ops.append({"op": "wait", "reg": "", "off": 0, "mask": 0, "value": _num(t[1]), "timeout": 0})
            else:
                errs.append(f"Line {ln}: cannot read “{line}”. Use write, read, poll, expect or wait.")
        except (ValueError, IndexError):
            errs.append(f"Line {ln}: a number is missing or malformed in “{line}”.")
    return ops, errs


def script_header(rm: dict, ops: list[dict], base: int = USER_BASE) -> str:
    rows = ",\n".join(
        f'    {{{OPS[o["op"]]}u, 0x{o["off"]:03X}u, 0x{o["mask"]:08X}u, 0x{o["value"] & 0xFFFFFFFF:08X}u, {int(o["timeout"])}u, "{o["reg"]}"}}'
        for o in ops) or '    {0u, 0u, 0u, 0u, 0u, ""}'
    return (f"/* Generated by OCA Chiplet Composer: register script for {rm.get('name')}. Do not edit. */\n"
            "#pragma once\n#include <stdint.h>\n"
            f'#define OCA_LOGIC_NAME "{rm.get("name")}"\n'
            f"#define OCA_LOGIC_BASE 0x{base:08X}ULL\n"
            "enum { OP_WRITE = 1, OP_READ = 2, OP_POLL = 3, OP_EXPECT = 4, OP_WAIT = 5 };\n"
            "typedef struct { uint32_t op, off, mask, value, timeout; const char *name; } oca_step_t;\n"
            f"#define OCA_SCRIPT_LEN {len(ops)}u\n"
            f"static const oca_step_t oca_script[] = {{\n{rows}\n}};\n")
